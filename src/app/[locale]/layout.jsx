import { notFound } from "next/navigation";
import { getMessages, setRequestLocale } from "next-intl/server";
import { hasLocale, NextIntlClientProvider } from "next-intl";
import { routing } from "@/i18n/routing";
import { Roboto } from "next/font/google";
import localFont from "next/font/local";
import "../globals.css";

import NavBar from "@/components/layout/NavBar";
import NavbarMobile from "@/components/layout/NavbarMobile";
import Footer from "@/components/layout/Footer";
import ReactQueryProvider from "@/lib/ReactQueryProvider";
import LocaleQueryInvalidator from "@/components/layout/LocaleQueryInvalidator";
import { Suspense } from "react";
import SplashScreen from "@/components/splashScreen/SplashScreen";
import AuthModals from "@/components/auth/AuthModals";
import NotificationsProvider from "@/components/notifications/NotificationsProvider";
import { Toaster } from "react-hot-toast";
import CookieConsent from "@/components/CookieConsent";
import { SITE_URL, DEFAULT_OG_IMAGE } from "@/lib/seo";

// --- Fonts Setup ---

// Roboto is the Latin body font. Only the weights the UI actually uses are
// loaded (the previous 6 weights × normal+italic = 12 files triggered the
// "preloaded but not used" warnings in note 9).
const roboto = Roboto({
  subsets: ["latin"],
  weight: ["300", "400", "500", "600", "700"],
  variable: "--font-roboto",
  display: "swap",
});

const ping = localFont({
  src: [
    {
      path: "../../../public/fonts/ping-ar/alfont_com_PingARLT-Thin.otf",
      weight: "100",
      style: "normal",
    },
    {
      path: "../../../public/fonts/ping-ar/alfont_com_PingARLT-Light.otf",
      weight: "300",
      style: "normal",
    },
    {
      path: "../../../public/fonts/ping-ar/alfont_com_PingARLT-Regular.otf",
      weight: "400",
      style: "normal",
    },
    {
      path: "../../../public/fonts/ping-ar/alfont_com_PingARLT-Bold.otf",
      weight: "700",
      style: "normal",
    },
  ],
  variable: "--font-ping-ar",
  display: "swap",
  // Arabic-only font: don't preload it on English pages (~600 KB wasted).
  preload: false,
});

// Root metadata. `metadataBase` makes the relative OG/canonical URLs absolute;
// the title template appends "| Velvet" to every child page title.
const SEO_BY_LOCALE = {
  en: {
    title: "Velvet — Women's, Girls' & Boys' Fashion",
    description:
      "Discover the latest women's, girls' and boys' fashion at Velvet. Shop new arrivals, jackets, dresses and more with delivery across Syria.",
  },
  ar: {
    title: "فيلفت — أزياء نسائية وبناتية وصبيانية",
    description:
      "تسوّقي أحدث صيحات الموضة النسائية والبناتية والصبيانية من فيلفت. اكتشفي الوصولات الجديدة والجاكيتات والفساتين والمزيد مع التوصيل داخل سوريا.",
  },
};

export async function generateMetadata({ params }) {
  const { locale } = await params;
  const seo = SEO_BY_LOCALE[locale] ?? SEO_BY_LOCALE.en;

  return {
    metadataBase: new URL(SITE_URL),
    title: {
      default: seo.title,
      template: "%s | Velvet",
    },
    description: seo.description,
    applicationName: "Velvet",
    openGraph: {
      type: "website",
      siteName: "Velvet",
      locale: locale === "ar" ? "ar_SY" : "en_US",
      alternateLocale: locale === "ar" ? "en_US" : "ar_SY",
      title: seo.title,
      description: seo.description,
      images: [
        {
          url: DEFAULT_OG_IMAGE,
          width: 1200,
          height: 630,
          alt: "Velvet",
        },
      ],
    },
    twitter: {
      card: "summary_large_image",
      title: seo.title,
      description: seo.description,
      images: [DEFAULT_OG_IMAGE],
    },
    robots: {
      index: true,
      follow: true,
      googleBot: {
        index: true,
        follow: true,
        "max-image-preview": "large",
      },
    },
  };
}

export async function generateStaticParams() {
  return routing.locales.map((locale) => ({ locale }));
}

export default async function RootLayout({ children, params }) {
  const { locale } = await params;
  setRequestLocale(locale);

  if (!hasLocale(routing.locales, locale)) {
    notFound();
  }

  const fontClass = locale === "ar" ? ping.className : roboto.className;
  const messages = await getMessages();

  // suppressHydrationWarning on <html>: the inline splash script below adds
  // the "show-splash" class to <html> in the browser before React hydrates,
  // so the DOM intentionally differs from the server HTML.
  return (
    <html lang={locale} dir={locale === "ar" ? "rtl" : "ltr"} suppressHydrationWarning>
      <head>
        {/* CSS rule applied IMMEDIATELY on first byte parsed */}
        <style
          dangerouslySetInnerHTML={{
            __html: `
              html.show-splash body > *:not(#instant-splash-screen) {
                visibility: hidden !important;
              }
            `,
          }}
        />
        {/* Instant blocking script before body starts */}
        <script
          dangerouslySetInnerHTML={{
            __html: `
              (function() {
                try {
                  if (!sessionStorage.getItem('hasSeenSplash')) {
                    document.documentElement.classList.add('show-splash');
                  }
                } catch(e) {}
              })();
            `,
          }}
        />
      </head>
      <body
        className={`${fontClass} ${ping.variable} ${roboto.variable} antialiased`}
      >
        {/*                                        👆 added roboto.variable */}

        <SplashScreen />

        <ReactQueryProvider>
          <NextIntlClientProvider locale={locale} messages={messages}>
            <LocaleQueryInvalidator />

            {/*
              FCM root provider — registers the SW + token, listens for
              messages. It MUST wrap the navbars too: the bell and its
              dropdown live in NavBar/NavbarMobile and read the permission,
              token and test helpers from this context. Mounting the provider
              only around <main> made the bell fall back to the context
              defaults ("unsupported" on every test, "guest", no token).
            */}
            <NotificationsProvider>
              <Suspense fallback={<div className="h-20 w-full" />}>
                <NavBar />
              </Suspense>

              <div className="lg:hidden block">
                <Suspense fallback={<div className="h-16 w-full" />}>
                  <NavbarMobile />
                </Suspense>
              </div>

              <Toaster
                position="top-center"
                toastOptions={{
                  style: { marginTop: "5rem" },
                  duration: 3000,
                }}
              />

              <main>{children}</main>
              <AuthModals />
              <Footer />
              <CookieConsent />
            </NotificationsProvider>
          </NextIntlClientProvider>
        </ReactQueryProvider>
      </body>
    </html>
  );
}